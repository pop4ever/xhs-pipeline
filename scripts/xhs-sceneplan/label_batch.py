    if not files:
        print(f"[{idx}] 底图缺失, 跳过")
        continue
    img = Image.open(os.path.join(SRC, files[0])).convert("RGBA")
    W, H = img.size
    overlay = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(overlay)
    for label, fx, fy in items:
        x, y = int(fx * W), int(fy * H)
        d.line([(x, y), (x, y - 18)], fill=(0, 0, 0, 200), width=2)
        d.ellipse([x - 5, y - 5, x + 5, y + 5], fill=(200, 40, 40, 255))
        label_box(d, x, y - 60, label, FONT)
    final = Image.alpha_composite(img, overlay)
    out = os.path.join(OUT, f"{PREFIX}-{idx:02d}-labeled.png")
    final.convert("RGB").save(out)
    print(f"✅ {out}")
